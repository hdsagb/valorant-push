"""AES-256-GCM 加密层测试。"""
from __future__ import annotations

import base64

from conftest import TEST_MASTER_KEY
from push_server import crypto


def test_roundtrip_and_format(data_dir):
    cipher = crypto.encrypt_text("邮箱授权码123")
    assert cipher.startswith("enc:v1:")
    nonce_b64, ct_b64 = cipher[len("enc:v1:"):].split(":", 1)
    assert len(base64.b64decode(nonce_b64, validate=True)) == 12
    assert crypto.decrypt_text(cipher) == "邮箱授权码123"


def test_each_encryption_uses_fresh_nonce(data_dir):
    a = crypto.encrypt_text("同文")
    b = crypto.encrypt_text("同文")
    assert a != b
    assert crypto.decrypt_text(a) == crypto.decrypt_text(b) == "同文"


def test_encrypt_is_idempotent(data_dir):
    once = crypto.encrypt_text("值")
    assert crypto.encrypt_text(once) == once


def test_empty_passthrough(data_dir):
    assert crypto.encrypt_text("") == ""
    assert crypto.decrypt_text("") == ""


def test_decrypt_malformed_returns_empty(data_dir):
    assert crypto.decrypt_text("enc:v1:!!!:!!!") == ""
    assert crypto.decrypt_text("enc:v1:AAAA") == ""  # 缺一段
    assert crypto.decrypt_text("普通值") == "普通值"  # 无前缀原样


def test_decrypt_with_wrong_key_returns_empty(data_dir, monkeypatch):
    cipher = crypto.encrypt_text("机密")
    monkeypatch.setenv("VAL_SERVER_MASTER_KEY", base64.b64encode(bytes(range(31, 63))).decode("ascii"))
    crypto.reset_key_cache()
    try:
        assert crypto.decrypt_text(cipher) == ""
    finally:
        crypto.reset_key_cache()


def test_fields_roundtrip(data_dir):
    mapping = {"userId": "u1", "tid": "t1", "flag": 3}
    enc = crypto.encrypt_fields(mapping)
    assert enc["userId"].startswith("enc:v1:")
    assert enc["tid"].startswith("enc:v1:")
    assert enc["flag"] == 3  # 非字符串原样
    assert crypto.decrypt_fields(enc)["userId"] == "u1"
    assert crypto.decrypt_fields(enc)["flag"] == 3


def test_env_key_takes_priority_over_key_file(data_dir):
    (data_dir / "master.key").write_bytes(b"x" * 32)  # 文件里放一个"错误"的密钥
    assert crypto.load_master_key() == base64.b64decode(TEST_MASTER_KEY)
    assert crypto.decrypt_text(crypto.encrypt_text("值")) == "值"


def test_key_file_autogenerated_and_reused(data_dir, monkeypatch):
    monkeypatch.delenv("VAL_SERVER_MASTER_KEY", raising=False)
    crypto.reset_key_cache()
    try:
        assert crypto.encrypt_text("值").startswith("enc:v1:")
        key_file = data_dir / "master.key"
        assert key_file.exists()
        assert len(key_file.read_bytes()) == 32
        first = crypto.load_master_key()
        crypto.reset_key_cache()
        assert crypto.load_master_key() == first  # 第二次读文件，不重新生成
        assert crypto.decrypt_text(crypto.encrypt_text("再试")) == "再试"
    finally:
        crypto.reset_key_cache()


def test_invalid_env_key_raises(data_dir, monkeypatch):
    monkeypatch.setenv("VAL_SERVER_MASTER_KEY", "not-base64!!!")
    crypto.reset_key_cache()
    try:
        import pytest

        with pytest.raises(crypto.CryptoError):
            crypto.load_master_key()
    finally:
        crypto.reset_key_cache()


def test_wrong_length_env_key_raises(data_dir, monkeypatch):
    monkeypatch.setenv("VAL_SERVER_MASTER_KEY", base64.b64encode(b"0123456789abcdef").decode("ascii"))
    crypto.reset_key_cache()
    try:
        import pytest

        with pytest.raises(crypto.CryptoError):
            crypto.load_master_key()
    finally:
        crypto.reset_key_cache()


def test_mask_helpers():
    assert crypto.mask_email("alice@qq.com") == "a***@qq.com"
    assert crypto.mask_email("") == ""
    assert crypto.mask_identifier("JA-09db2000480f479a") == "***479a"
    assert crypto.mask_identifier("ab") == "***ab"
    assert crypto.mask_identifier("") == ""
